/** The catalogue of each shipped locale. */
export const CATALOGUES: Record<Locale, Record<MessageKey, string>> = {
  en,
  'pt-BR': ptBR,
  es,
}

/** Replaces `{name}` placeholders in a message. */
export function format(message: string, values?: Record<string, string | number>): string {
  if (!values) return message
  return message.replace(/\{(\w+)\}/gu, (match, key: string) =>
    key in values ? String(values[key]) : match,
  )
}

/** Looks a message up in a catalogue. */
export function translate(
  locale: Locale,
  key: MessageKey,
  values?: Record<string, string | number>,
): string {
  return format(CATALOGUES[locale]?.[key] ?? CATALOGUES.en[key] ?? key, values)
}

/** The locale a system language maps to. */
export function normalizeLocale(language: string | undefined): Locale {
  if (!language) return 'en'
  const lower = language.toLowerCase()
  if (lower.startsWith('pt')) return 'pt-BR'
  if (lower.startsWith('es')) return 'es'
  return 'en'
}

